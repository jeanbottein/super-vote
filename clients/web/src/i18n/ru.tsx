const number = (count: number) => formatNumber('ru', count);
/** The noun in the form a count asks for: 1 голос, 2 голоса, 5 голосов. */
const noun = (count: number, one: string, few: string, many: string) => pluralForm('ru', count, { one, few, many, other: many });
const counted = (count: number, one: string, few: string, many: string) => `${number(count)} ${noun(count, one, few, many)}`;

function inWords(at: number): string {
  const { count, unit } = waitUntil(at);
  return unit === 'minute' ? counted(count, 'минуту', 'минуты', 'минут') : counted(count, 'час', 'часа', 'часов');
}

